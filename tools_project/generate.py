def generate(out: Path, root: Path = ROOT, strict: bool = False) -> str:
    """iolistgen и список устройств в каталог ``out``; вывод iolistgen — результат."""
    output = run_iolistgen(out, root, strict)
    write_device_list(out)
    return output


def drift(root: Path = ROOT) -> list[str]:
    """Файлы генерации, которые отличаются от свежей генерации во временный каталог (пусто — дрейфа нет)."""
    with tempfile.TemporaryDirectory(prefix="kns-gen-") as tmp:
        out = Path(tmp)
        previous = root / PERSIST_FILE
        if previous.is_file():  # сверка persist_check с GVL_Persist репозитория
            (out / PERSIST_FILE).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(previous, out / PERSIST_FILE)
        generate(out, root, strict=True)
        result = []
        for rel in GENERATED_FILES:
            fresh, current = out / rel, root / rel
            if not current.is_file():
                result.append(f"{rel.as_posix()}: нет в репозитории")
            elif not filecmp.cmp(fresh, current, shallow=False):
                result.append(f"{rel.as_posix()}: отличается от генерации")
        return result


def main(argv: Sequence[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):  # консоль Windows по умолчанию — cp1251
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(prog="generate.py", description="Генерация слоя устройств КНС-1 по перечню")
    parser.add_argument("--check", action="store_true", help="проверить дрейф: генерация во временный каталог")
    parser.add_argument("--strict", action="store_true", help="предупреждения iolistgen — ошибка (как в CI)")
    args = parser.parse_args(argv)
    try:
        if args.check:
            problems = drift()
            for line in problems:
                print(f"generate: {line}")
            if problems:
                print("generate: дрейф генерации — выполните python tools_project/generate.py и закоммитьте файлы")
                return 1
            print(f"generate: дрейфа нет ({len(GENERATED_FILES)} файлов)")
            return 0
        print(generate(ROOT, ROOT, strict=args.strict))
        print(f"generate: {DEVICE_LIST_GVL.as_posix()}, {DEVICE_LIST_PRG.as_posix()} — по GVL_DevIdx")
    except GenerateError as exc:
        print(f"generate: {exc}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
