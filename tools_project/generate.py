#!/usr/bin/env python3
"""Генерация слоя устройств КНС-1 из перечня сигналов (docs/DESIGN.md, разделы 4.5, 4.6; ARCHITECTURE, раздел 3.1).

Одна команда после любой правки ``docs/03_io_list.csv``:

1. ``iolistgen generate docs/03_io_list.csv --out . --config iolistgen.toml`` — ST в ``src/*/Generated``
   (``GVL_IO``, ``GVL_Devices``, ``GVL_Hmi``, ``GVL_Persist`` с блоком станции из ``persist_extra``,
   ``GVL_CfgProject``, ``GVL_DevIdx``, ``PRG_Devices``, ``PRG_ApplyProjectCfg``), карты Modbus, импорт SCADA,
   ``docs/alarms.csv``, ``docs/03_io_list.md``. Опции ``alarm-list.templates`` и ``scada-csv.templates`` =
   ``none`` передаются через ``--set``: значение ``none`` из ``iolistgen.toml`` iolistgen 0.2.0 читает как
   путь (docs/ASSUMPTIONS.md, К3-04);
2. список устройств проекта ``GVL_DeviceList`` и ``PRG_DeviceList`` (решение D-11) — по ``GVL_DevIdx``,
   который только что записал iolistgen: теги, ``dev_no`` и типы по возрастанию ``dev_no``.

``--check`` — то же во временный каталог (с прежним ``GVL_Persist`` для сверки ``persist_check`` и с
``--strict``) и побайтное сравнение с файлами репозитория: дрейф генерации — код выхода 1 (CI).

iolistgen ищется так: модуль ``iolistgen`` в окружении; иначе каталог из ``IOLISTGEN_REPO``; иначе соседний
репозиторий ``../iolistgen`` (у рабочей копии ``git worktree`` в ``_wt/`` — ``../../iolistgen``).
"""

from __future__ import annotations

import argparse
import filecmp
import importlib.util
import os
import re
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IO_LIST = Path("docs/03_io_list.csv")
CONFIG = Path("iolistgen.toml")
# Опции, которые нельзя задать в iolistgen.toml (значение none читается как путь от каталога настроек)
IOLISTGEN_SETS = ("alarm-list.templates=none", "scada-csv.templates=none")
GEN_GVL_DIR = Path("src/GVLs/Generated")
GEN_POU_DIR = Path("src/POUs/Generated")
DEVIDX_FILE = GEN_GVL_DIR / "GVL_DevIdx.gvl.st"
PERSIST_FILE = GEN_GVL_DIR / "GVL_Persist.pvl.st"
DEVICE_LIST_GVL = GEN_GVL_DIR / "GVL_DeviceList.gvl.st"
DEVICE_LIST_PRG = GEN_POU_DIR / "PRG_DeviceList"
# Файлы, которые пишет iolistgen с настройками проекта (iolistgen.toml) — для проверки дрейфа
IOLISTGEN_FILES = (
    GEN_GVL_DIR / "GVL_IO.gvl.st",
    GEN_GVL_DIR / "GVL_DevIdx.gvl.st",
    GEN_GVL_DIR / "GVL_Hmi.gvl.st",
    PERSIST_FILE,
    GEN_GVL_DIR / "GVL_CfgProject.gvl.st",
    GEN_GVL_DIR / "GVL_Devices.gvl.st",
    GEN_POU_DIR / "PRG_Devices" / "PRG_Devices.decl.st",
    GEN_POU_DIR / "PRG_Devices" / "PRG_Devices.impl.st",
    GEN_POU_DIR / "PRG_ApplyProjectCfg" / "PRG_ApplyProjectCfg.decl.st",
    GEN_POU_DIR / "PRG_ApplyProjectCfg" / "PRG_ApplyProjectCfg.impl.st",
    Path("docs/modbus_master_map.csv"),
    Path("docs/modbus_slave_map.csv"),
    Path("docs/modbus_map.md"),
    Path("scada/scada_tags.csv"),
    Path("scada/scada_alarms.csv"),
    Path("docs/alarms.csv"),
    Path("docs/03_io_list.md"),
)
PROJECT_FILES = (
    DEVICE_LIST_GVL,
    DEVICE_LIST_PRG / "PRG_DeviceList.decl.st",
    DEVICE_LIST_PRG / "PRG_DeviceList.impl.st",
)
GENERATED_FILES = IOLISTGEN_FILES + PROJECT_FILES

HEADER = "// AUTO-GENERATED by tools_project/generate.py — не редактировать; источник: docs/03_io_list.csv"
INDENT = "    "
MAX_LINE = 120
# Строка GVL_DevIdx: «    P101 : UINT := 11;  // MotorVfd · Насос Н1»
_DEVIDX_RE = re.compile(r"^\s+([A-Z][A-Z0-9_]*)\s*:\s*UINT\s*:=\s*(\d+);\s*//\s*([A-Za-z]+)\s*·\s*(.*)$")


class GenerateError(Exception):
    """Ошибка генерации: сообщение для консоли, код выхода 1."""


@dataclass(frozen=True)
class Device:
    """Устройство перечня: тег, номер dev_no, тип PL.E_DeviceType, описание."""

    tag: str
    dev_no: int
    dev_type: str
    description: str


# --------------------------------------------------------------------------------------------------
# iolistgen
# --------------------------------------------------------------------------------------------------


def find_iolistgen(root: Path = ROOT) -> Path | None:
    """Каталог, который нужно добавить в PYTHONPATH для ``python -m iolistgen``; ``None`` — модуль уже доступен.

    ``GenerateError`` — iolistgen не найден.
    """
    raw = os.environ.get("IOLISTGEN_REPO")
    candidates = [Path(raw)] if raw else [root.parent / "iolistgen", root.parent.parent / "iolistgen"]
    for candidate in candidates:
        if (candidate / "iolistgen" / "__init__.py").is_file():
            return candidate.resolve()
    if importlib.util.find_spec("iolistgen") is not None:
        return None
    raise GenerateError(
        "iolistgen не найден: установите пакет (pipx install <iolistgen>) или задайте IOLISTGEN_REPO "
        "(каталог репозитория iolistgen)"
    )


def iolistgen_command(out: Path, root: Path = ROOT, strict: bool = False) -> list[str]:
    """Команда генерации с настройками проекта (запускать с cwd = корень репозитория)."""
    cmd = [sys.executable, "-m", "iolistgen", "generate", str(IO_LIST), "--out", str(out), "--config", str(CONFIG)]
    for item in IOLISTGEN_SETS:
        cmd += ["--set", item]
    if strict:
        cmd.append("--strict")
    return cmd


def run_iolistgen(out: Path, root: Path = ROOT, strict: bool = False) -> str:
    """Запустить iolistgen; вывод консоли — результат. ``GenerateError`` — код выхода не 0."""
    repo = find_iolistgen(root)
    env = dict(os.environ)
    env["PYTHONIOENCODING"] = "utf-8"
    if repo is not None:
        env["PYTHONPATH"] = os.pathsep.join(p for p in (str(repo), env.get("PYTHONPATH", "")) if p)
    proc = subprocess.run(
        iolistgen_command(out, root, strict),
        cwd=root,
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    output = (proc.stdout + proc.stderr).strip()
    if proc.returncode != 0:
        raise GenerateError(f"iolistgen завершился с кодом {proc.returncode}:\n{output}")
    return output


