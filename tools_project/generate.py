# Список устройств проекта: GVL_DeviceList, PRG_DeviceList (DESIGN, раздел 4.5)
# --------------------------------------------------------------------------------------------------


def read_devices(devidx_text: str) -> list[Device]:
    """Устройства из ``GVL_DevIdx`` (вывод iolistgen) по возрастанию ``dev_no``."""
    devices = []
    for line in devidx_text.splitlines():
        m = _DEVIDX_RE.match(line)
        if m is not None:
            devices.append(Device(m.group(1), int(m.group(2)), m.group(3), m.group(4).strip()))
    if not devices:
        raise GenerateError(f"{DEVIDX_FILE}: нет устройств (формат вывода iolistgen изменился?)")
    devices.sort(key=lambda d: d.dev_no)
    return devices


def _wrap_items(head: str, items: Sequence[str], tail: str) -> list[str]:
    """``head [a, b, ...] tail`` по строкам не длиннее MAX_LINE; продолжение — с отступом в два уровня."""
    lines: list[str] = []
    current = head + "["
    for index, item in enumerate(items):
        piece = item + (", " if index < len(items) - 1 else "]" + tail)
        if len(current) + len(piece.rstrip()) > MAX_LINE and current.strip():
            lines.append(current.rstrip())
            current = INDENT * 2
        current += piece
    lines.append(current.rstrip())
    return lines


def device_list_gvl(devices: Sequence[Device]) -> str:
    """Текст ``GVL_DeviceList.gvl.st``."""
    count = "GVL_DeviceList.DEVICE_COUNT"
    lines = [
        HEADER,
        "// Назначение: список устройств перечня для общего сброса и квитирования, сводки тревог, аудита режимов",
        "//             и кодов тревог в CSV журнала (решение D-11): теги, dev_no и типы по возрастанию dev_no,",
        "//             позиция устройства в списке (IDX_<TAG>) и интерфейсы aitfDevice, которые присваивает",
        "//             PRG_DeviceList каждый цикл (ссылки переживают онлайн-изменение).",
        "{attribute 'qualified_only'}",
        "VAR_GLOBAL CONSTANT",
        f"{INDENT}DEVICE_COUNT : UINT := {len(devices)};  // устройств в перечне сигналов",
    ]
    for index, dev in enumerate(devices, 1):
        line = f"{INDENT}IDX_{dev.tag} : UINT := {index};  // {dev.dev_no} · {dev.description}"
        lines.append(line[:MAX_LINE].rstrip())
    reason = "имя как у переменной списка (DESIGN, раздел 4.5): массив-константа"
    lines.append(f"{INDENT}// lint:allow STL007 {reason}")
    lines += _wrap_items(
        f"{INDENT}asTag : ARRAY[1..{count}] OF STRING(GVL_Const.TAG_LEN) := ",
        [f"'{d.tag}'" for d in devices],
        ";",
    )
    lines.append(f"{INDENT}// lint:allow STL007 {reason}")
    lines += _wrap_items(
        f"{INDENT}auiDevNo : ARRAY[1..{count}] OF UINT := ", [f"GVL_DevIdx.{d.tag}" for d in devices], ";"
    )
    lines.append(f"{INDENT}// lint:allow STL007 {reason}")
    lines += _wrap_items(
        f"{INDENT}aeDevType : ARRAY[1..{count}] OF PL.E_DeviceType := ",
        [f"PL.E_DeviceType.{d.dev_type}" for d in devices],
        ";",
    )
    lines += [
        "END_VAR",
        "VAR_GLOBAL",
        f"{INDENT}aitfDevice : ARRAY[1..{count}] OF PL.I_Device;  // присваивает PRG_DeviceList каждый цикл",
        "END_VAR",
    ]
    return "\n".join(lines) + "\n"


def device_list_prg(devices: Sequence[Device]) -> tuple[str, str]:
    """Объявление и тело ``PRG_DeviceList``."""
    decl = "\n".join(
        [
            HEADER,
            "// Назначение: интерфейсы устройств перечня в GVL_DeviceList.aitfDevice — каждый цикл, до PRG_Station",
            "//             (MainTask); порядок — GVL_DeviceList (по возрастанию dev_no).",
            "// Автор:      tools_project/generate.py (генератор по перечню сигналов)",
            "// Версия:     0.1.0",
            "// Документ:   docs/DESIGN.md, раздел 4.5",
            "PROGRAM PRG_DeviceList",
        ]
    )
    body = [f"GVL_DeviceList.aitfDevice[GVL_DeviceList.IDX_{d.tag}] := GVL_Devices.fb{d.tag};" for d in devices]
    return decl + "\n", "\n".join(body) + "\n"


def write_device_list(out: Path) -> None:
    """Записать ``GVL_DeviceList`` и ``PRG_DeviceList`` по ``GVL_DevIdx`` в каталоге ``out``."""
    devices = read_devices((out / DEVIDX_FILE).read_text(encoding="utf-8"))
    files = {DEVICE_LIST_GVL: device_list_gvl(devices)}
    decl, impl = device_list_prg(devices)
    files[DEVICE_LIST_PRG / "PRG_DeviceList.decl.st"] = decl
    files[DEVICE_LIST_PRG / "PRG_DeviceList.impl.st"] = impl
    for rel, text in files.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        data = text.encode("utf-8")
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)


