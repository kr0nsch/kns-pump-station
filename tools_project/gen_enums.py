#!/usr/bin/env python3
"""Таблица перечислений для сценариев ПМИ: ``scenarios/kns_scenarios/enums.py`` (DESIGN, раздел 14.3).

Литералы перечислений в сценариях (``E_MotorState.Fault``, ``E_ControlAct.Float``) исполнитель переводит
в числа по этой таблице: в файлах сценариев нет «магических» чисел. Источники (поздний перекрывает
ранний): снимок plc-process-lib ``tools_project/data/plc_process_lib.json``, перечисления DESIGN (блоки ST
и таблицы раздела 3), DUT проекта ``src/DUTs``. Значения без явного числа не попадают в таблицу.

``python tools_project/gen_enums.py`` — записать; ``--check`` — сверить с файлом (CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path

import check_docs_consistency as C

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "scenarios" / "kns_scenarios" / "enums.py"


def collect(root: Path = ROOT) -> dict[str, dict[str, int]]:
    """Перечисления: имя типа → {значение: число}."""
    sources = [C.StIndex.from_json(json.loads(C.LIB_SNAPSHOT.read_text(encoding="utf-8")))]
    design = root / "docs" / "DESIGN.md"
    if design.exists():
        sources.append(C.design_index(C.Doc.load(design)))
    project = C.StIndex()
    for path in sorted((root / "src" / "DUTs").rglob("*.dut.st")):
        project.merge(C.parse_st(path.read_text(encoding="utf-8")))
    sources.append(project)
    enums: dict[str, dict[str, int]] = {}
    for index in sources:
        for name, t in index.types.items():
            if t.kind != "enum":
                continue
            values = {k: v for k, v in t.values.items() if v is not None}
            if values:
                enums[name] = values
    return {name: dict(sorted(vals.items(), key=lambda kv: (kv[1], kv[0]))) for name, vals in sorted(enums.items())}


def render(enums: dict[str, dict[str, int]]) -> str:
    lines = [
        '"""Перечисления ПЛК для литералов сценариев ПМИ (E_<Тип>.<Значение> → число).',
        "",
        "AUTO-GENERATED by tools_project/gen_enums.py — не редактировать; источники: снимок plc-process-lib,",
        "docs/DESIGN.md (раздел 3), src/DUTs.",
        '"""',
        "",
        "ENUMS: dict[str, dict[str, int]] = {",
    ]
    for name, values in enums.items():
        lines.append(f'    "{name}": {{')
        lines += [f'        "{k}": {v},' for k, v in values.items()]
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen_enums.py", description="Таблица перечислений для сценариев ПМИ")
    parser.add_argument("--check", action="store_true", help="сверить с файлом, не записывая")
    args = parser.parse_args(argv)
    text = render(collect())
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"gen_enums: {OUT.relative_to(ROOT).as_posix()} устарел — python tools_project/gen_enums.py")
            return 1
        print("gen_enums: таблица перечислений актуальна")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_enums: записан {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
